#!/usr/bin/env bash
# The files copied in from the Department of Internal Arguments: each one
# matches its sha256 in pins.yaml, says which release made it, names an exact
# model, and is plain ASCII. A changed file means a new pin, never an edit.
#
#   bash tests/check-doia.sh

set -uo pipefail
. "$(dirname "$0")/lib.sh"

pins="$REPO/home/.chezmoidata/pins.yaml"

section "pin"
commit=$(sed -n '/^  doia:/,/^  [a-z]/s/^    commit: \([0-9a-f]*\)$/\1/p' "$pins")
tag=$(sed -n '/^  doia:/,/^  [a-z]/s/^    tag: \(.*\)$/\1/p' "$pins")
[[ "$commit" =~ ^[0-9a-f]{40}$ ]] && pass "pins a full commit ($tag)" || fail "pins a full commit" "${commit:-none}"

# "path sha256" for each file under doia.files, and no other pin's.
files=$(sed -n '/^  doia:/,/^  [a-z]/s/^      \([^:]*\): \([0-9a-f]\{64\}\)$/\1 \2/p' "$pins")
count=$(grep -c . <<< "$files")
[ "$count" = 5 ] && pass "lists five files" || fail "lists five files" "$count"

section "files"
while read -r path want; do
  [ -n "$path" ] || continue
  f="$REPO/$path"
  if [ ! -f "$f" ]; then fail "$path exists"; continue; fi
  got=$( (sha256sum "$f" 2>/dev/null || shasum -a 256 "$f") | cut -c1-64)
  [ "$got" = "$want" ] && pass "$path matches its pin" || fail "$path matches its pin" "got $got"
  grep -q "Generated by scripts/generate.py (release ${tag#v})" "$f" \
    && pass "$path says release ${tag#v}" || fail "$path says release ${tag#v}"
  LC_ALL=C grep -q '[^[:print:][:space:]]' "$f" \
    && fail "$path is plain ASCII" "$(LC_ALL=C grep -n '[^[:print:][:space:]]' "$f" | head -3)" \
    || pass "$path is plain ASCII"
done <<< "$files"

agent="$REPO/home/dot_claude/agents/adversarial-reviewer.md"
model=$(sed -n '2,/^---$/s/^model: \(.*\)$/\1/p' "$agent")
case "$model" in
  claude-*) pass "the agent pins an exact model ($model)" ;;
  *) fail "the agent pins an exact model" "${model:-none}" ;;
esac

section "licence"
for f in department-of-internal-arguments-Apache-2.0.txt department-of-internal-arguments-NOTICE.txt; do
  [ -s "$REPO/LICENSES/$f" ] && pass "LICENSES/$f" || fail "LICENSES/$f"
done
grep -q "$commit" "$REPO/LICENSES/README.md" && pass "LICENSES/README.md names the pinned commit" \
  || fail "LICENSES/README.md names the pinned commit"

section "routing"
rules="$REPO/home/dot_claude/routing.md"
grep -q 'adversarial-reviewer.md' "$rules" && pass "routing.md sends security-sensitive DEEP work to it" \
  || fail "routing.md sends security-sensitive DEEP work to it"
for pack in gha-security-dast python-untrusted-input threat-model linux-platform; do
  grep -q "pack-$pack" "$rules" && pass "routing.md names pack-$pack" || fail "routing.md names pack-$pack"
done

summary
